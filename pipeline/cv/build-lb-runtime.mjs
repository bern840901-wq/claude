// Builds /lb.js: the CV's line-break rules (linebreak.mjs) for pages whose text
// is rendered at run time — the portfolio (/home/) and the film page (/).
//
// The script walks the page's text nodes and rewrites each one in place with
// invisible characters only: WORD JOINER where a break must not happen (inside
// a Chinese word, a name, a number and its unit, before a separator …) and a
// no-break space where a space must not break. The visible text is unchanged.
// It re-runs when the page re-renders (language switch, opened card, expanded
// timeline) through a MutationObserver.
import fs from 'fs';

const here = new URL('.', import.meta.url);
const src = fs.readFileSync(new URL('linebreak.mjs', here), 'utf8');
const terms = fs.readFileSync(new URL('zh_terms.json', here), 'utf8');
const names = fs.readFileSync(new URL('nobreak_names.json', here), 'utf8');

const body = src
  .replace(/^import fs from 'fs';\n/m, '')
  .replace(/^const here = .*\n/m, '')
  .replace(/^const TERMS = .*\n/m, 'const TERMS = ' + terms.trim() + ';\n')
  .replace(/^const NAMES = .*\n/m, 'const NAMES = ' + names.trim() + ';\n')
  .replace(/^export function /gm, 'function ');
if (/readFileSync|import\.meta|^export /m.test(body)) throw new Error('linebreak.mjs changed shape; update build-lb-runtime.mjs');

const runtime = `/* lb.js — generated by pipeline/cv/build-lb-runtime.mjs from linebreak.mjs,
   zh_terms.json and nobreak_names.json. Do not edit by hand. */
(function () {
${body}
var WJ = '\\u2060', NBSP = '\\u00a0', NNBSP = '\\u202f';
var SKIP = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1, INPUT: 1, NOSCRIPT: 1, CODE: 1, PRE: 1, SVG: 1, svg: 1, title: 1 };
var INVIS = /[\\u2060\\u202f\\u200b]/g;
var done = new WeakMap();   // text node -> the value lb.js last wrote
var large = new WeakMap();  // element -> font-size >= 22px (display text)
var HG = /[\\uac00-\\ud7a3]/;
function apply(raw, koPage, large) {
  // the pages' CSS (text-wrap:pretty) already avoids a lone last word in Latin text;
  // large display text gets no last-word ties at all (a tied pair may not fit)
  var code = lbInfo(raw, { latinTail: false, tail: !large });
  var n = decodeN(code);
  var out = '';
  for (var i = 0; i < raw.length; i++) {
    var c = raw[i], a = raw[i - 1];
    if (i && c !== ' ' && a !== ' ') {
      if (n.has(i)) out += WJ;
      else if (!koPage && HG.test(a) && HG.test(c)) out += WJ;   // Korean words stay whole on every page
      else if ('・·/'.indexOf(a) >= 0) out += '\\u200b';         // keep-all gives no break after an unspaced ・ · /
    }
    if (c === ' ' && n.has(i + 1)) out += NBSP; else out += c;
  }
  return out;
}
function fix(node, koPage) {
  var v = node.nodeValue;
  if (!v || v.length < 2 || done.get(node) === v) return;
  var p = node.parentNode; if (!p || SKIP[p.nodeName] || (p.closest && p.closest('[data-nolb],svg'))) return;
  if (!/[\\u3400-\\u9fff\\uac00-\\ud7a3]|\\S \\S|\\d|[·・—×\\/(（\\-–]/.test(v)) { done.set(node, v); return; }
  var raw = v.replace(INVIS, '');
  var fs = large.get(p); if (fs === undefined) { fs = parseFloat(getComputedStyle(p).fontSize) >= 22; large.set(p, fs); }
  var next = apply(raw, koPage, fs);
  done.set(node, next);
  if (next !== v) node.nodeValue = next;
}
function run(root) {
  var koPage = (document.documentElement.lang || '').slice(0, 2) === 'ko';
  var w = document.createTreeWalker(root || document.body, NodeFilter.SHOW_TEXT);
  var t; while ((t = w.nextNode())) fix(t, koPage);
}
var queued = false, pending = [];
function schedule(node) { pending.push(node); if (queued) return; queued = true; requestAnimationFrame(function () { queued = false; var list = pending; pending = []; var koPage = (document.documentElement.lang || '').slice(0, 2) === 'ko'; for (var k = 0; k < list.length; k++) { var x = list[k]; if (!x.isConnected) continue; if (x.nodeType === 3) fix(x, koPage); else run(x); } }); }
function start() {
  run(document.body);
  new MutationObserver(function (ms) {
    for (var k = 0; k < ms.length; k++) {
      var m = ms[k];
      if (m.type === 'characterData') { if (done.get(m.target) !== m.target.nodeValue) schedule(m.target); }
      else for (var j = 0; j < m.addedNodes.length; j++) schedule(m.addedNodes[j]);
      if (m.type === 'attributes' && document.body) schedule(document.body);
    }
  // observe the Document itself: the portfolio's bundle loader replaces the whole
  // <html> element after this script has started
  }).observe(document, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['lang'] });
}
window.__lb = { info: lbInfo, decode: decodeN, apply: apply, run: run, opts: function (el) { return { latinTail: false, tail: !(parseFloat(getComputedStyle(el).fontSize) >= 22) }; } };
if (window.__LB_NOAUTO) return;   // measuring tools load the rules without touching the page
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
})();
`;
fs.writeFileSync('/home/user/claude/lb.js', runtime);
console.log('written lb.js', (runtime.length / 1024).toFixed(0) + 'KB');
